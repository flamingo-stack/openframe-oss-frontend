#!/usr/bin/env node

/**
 * Fetches the API and Chat GraphQL schemas via introspection and saves
 * their independent SDL files for the Relay compiler.
 *
 * Usage:
 *   npm run fetch-schema                                              # uses NEXT_PUBLIC_TENANT_HOST_URL from .env
 *   npm run fetch-schema -- --token <JWT>                             # with auth token
 *   GRAPHQL_TOKEN=<JWT> npm run fetch-schema                          # token via env
 *   npm run fetch-schema -- --endpoint http://localhost:4000/api/graphql
 *   npm run fetch-schema -- --endpoint http://localhost:4000/api/graphql --chat-endpoint http://localhost:4001/chat/graphql
 */

import { randomUUID } from 'node:crypto';
import { readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { assertValidSchema, buildClientSchema, getIntrospectionQuery, printSchema } from 'graphql';

// --- Parse CLI args ---
const args = process.argv.slice(2);
function getArg(name) {
  const idx = args.indexOf(`--${name}`);
  return idx !== -1 && args[idx + 1] ? args[idx + 1] : undefined;
}

// --- Load .env file for NEXT_PUBLIC_TENANT_HOST_URL ---
function loadDotEnv() {
  const envFiles = ['.env.local', '.env'];
  for (const file of envFiles) {
    try {
      const content = readFileSync(resolve(import.meta.dirname, '..', file), 'utf-8');
      for (const line of content.split('\n')) {
        const trimmed = line.trim();
        if (!trimmed || trimmed.startsWith('#')) continue;
        const eqIdx = trimmed.indexOf('=');
        if (eqIdx === -1) continue;
        const key = trimmed.slice(0, eqIdx).trim();
        const value = trimmed.slice(eqIdx + 1).trim();
        if (!process.env[key]) {
          process.env[key] = value;
        }
      }
    } catch {
      // file not found — skip
    }
  }
}

loadDotEnv();

const tenantHost = process.env.NEXT_PUBLIC_TENANT_HOST_URL || 'http://localhost:8080';
const apiEndpoint = getArg('endpoint') || `${tenantHost}/api/graphql`;
const chatEndpoint = getArg('chat-endpoint') || new URL('/chat/graphql', apiEndpoint).href;
const token = getArg('token') || process.env.GRAPHQL_TOKEN;
const schemas = [
  { endpoint: apiEndpoint, output: resolve(import.meta.dirname, '..', 'schema.graphql') },
  { endpoint: chatEndpoint, output: resolve(import.meta.dirname, '..', 'schema.chat.graphql') },
];

async function fetchSchema({ endpoint, output }) {
  console.log(`[fetch-schema] Fetching schema from ${endpoint} ...`);
  if (token) {
    console.log('[fetch-schema] Using Bearer token for authentication');
  }

  const headers = { 'Content-Type': 'application/json' };
  if (token) {
    headers.Authorization = `Bearer ${token}`;
  }

  const response = await fetch(endpoint, {
    method: 'POST',
    headers,
    body: JSON.stringify({ query: getIntrospectionQuery() }),
  });

  if (!response.ok) {
    throw new Error(`Introspection request failed: ${response.status} ${response.statusText}`);
  }

  const json = await response.json();

  if (json.errors?.length) {
    throw new Error(`GraphQL errors: ${json.errors.map(e => e.message).join(', ')}`);
  }

  const schema = buildClientSchema(json.data);
  assertValidSchema(schema);
  const sdl = printSchema(schema).replace(/^[ \t]+$/gm, '');

  const header = [
    '# Auto-generated by scripts/fetch-schema.mjs via introspection',
    `# Source: ${endpoint}`,
    `# Generated: ${new Date().toISOString()}`,
    '#',
    '# Do not edit manually. Re-run: npm run fetch-schema',
    '',
  ].join('\n');

  return { output, content: header + sdl + '\n' };
}

async function fetchSchemas() {
  const fetched = await Promise.all(schemas.map(fetchSchema));
  const staged = fetched.map(schema => ({ ...schema, temporary: `${schema.output}.${randomUUID()}.tmp` }));
  try {
    staged.forEach(writeStagedSchema);
    staged.forEach(replaceSchema);
  } finally {
    staged.forEach(removeStagedSchema);
  }
  fetched.forEach(schema => {
    console.log(`[fetch-schema] Schema written to ${schema.output}`);
  });
}

function writeStagedSchema(schema) {
  writeFileSync(schema.temporary, schema.content, 'utf-8');
}

function replaceSchema(schema) {
  renameSync(schema.temporary, schema.output);
}

function removeStagedSchema(schema) {
  rmSync(schema.temporary, { force: true });
}

fetchSchemas().catch(err => {
  console.error(`[fetch-schema] Failed:`, err.message);
  process.exit(1);
});
