#!/usr/bin/env node

/**
 * Reads the API and Chat schemas and emits independent enum modules in
 * Prisma-style — the value (const object) and the type
 * share the same name, so consumers can use either:
 *
 *   export const SubscriptionStatus = { ACTIVE: 'ACTIVE', ... } as const;
 *   export type SubscriptionStatus = (typeof SubscriptionStatus)[keyof typeof SubscriptionStatus];
 *
 *   // usage
 *   SubscriptionStatus.ACTIVE        // value
 *   const x: SubscriptionStatus      // type
 *
 * The outputs live in `src/generated/{schema-enums,chat-schema-enums}.ts` (gitignored). They stay
 * OUT of `src/__generated__/` on purpose — relay-compiler owns that directory
 * and prunes any file there that isn't a Relay artifact.
 * Run via `npm run generate-enums`; chained into `npm run build`.
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'graphql';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
function generateEnums(schemaFile, outputFile) {
  const doc = parse(readFileSync(resolve(ROOT, schemaFile), 'utf-8'));
  const enums = doc.definitions
    .filter(definition => definition.kind === 'EnumTypeDefinition')
    .sort((a, b) => a.name.value.localeCompare(b.name.value));
  const lines = enums.flatMap(definition => [
    `export const ${definition.name.value} = {`,
    ...(definition.values ?? []).map(value => `  ${value.name.value}: '${value.name.value}',`),
    '} as const;',
    `export type ${definition.name.value} = (typeof ${definition.name.value})[keyof typeof ${definition.name.value}];`,
    '',
  ]);
  const output = resolve(ROOT, 'src/generated', outputFile);
  mkdirSync(dirname(output), { recursive: true });
  writeFileSync(
    output,
    [`// @generated by scripts/generate-schema-enums.mjs from ${schemaFile} — DO NOT EDIT`, '', ...lines].join('\n'),
  );
  console.log(`Generated ${enums.length} enum(s) → ${output.replace(`${ROOT}/`, '')}`);
}

generateEnums('schema.graphql', 'schema-enums.ts');
generateEnums('schema.chat.graphql', 'chat-schema-enums.ts');
